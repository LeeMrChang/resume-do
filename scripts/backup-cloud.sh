#!/usr/bin/env bash
# The same helper is used during release and by the daily host timer.
set -Eeuo pipefail
umask 077

backup_data() {
  local destination=$1
  mkdir -m 700 "$destination"
  compose exec -T resume-db sh -c \
    'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysqldump --protocol=tcp -h127.0.0.1 -uroot --single-transaction --no-tablespaces --set-gtid-purged=OFF --hex-blob resume_do' \
    | gzip -1 > "$destination/database.sql.gz"
  gzip -t "$destination/database.sql.gz"
  # Use the released worker image's tar; do not depend on host volume mount paths.
  "${DOCKER[@]}" run --rm --network none --read-only --entrypoint tar \
    -v resume_do_cloud_files:/data:ro -v "$destination:/backup" \
    "resume-worker:$RESUME_DO_IMAGE_TAG" -czf /backup/files.tar.gz -C /data .
  tar -tzf "$destination/files.tar.gz" >/dev/null
  (cd "$destination" && sha256sum database.sql.gz files.tar.gz > SHA256SUMS)
  touch "$destination/COMPLETE"
}

# Sourcing only defines backup_data; the deployment script already owns the lock and pause.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  root=${1:-/home/ubuntu/resume-do}
  [[ "$root" =~ ^/[A-Za-z0-9_/-]+/resume-do$ ]] || { echo 'Invalid deployment root' >&2; exit 1; }
  test -f "$root/current/image.env"
  exec 9>"$root/deploy.lock"
  flock -n 9 || { echo 'Deployment/backup already running' >&2; exit 1; }
  # image.env is generated by the deployer and contains only a validated immutable tag.
  RESUME_DO_IMAGE_TAG=$(sed -n 's/^RESUME_DO_IMAGE_TAG=//p' "$root/current/image.env")
  [[ "$RESUME_DO_IMAGE_TAG" =~ ^ci-[a-f0-9]{40}-[0-9]+-[0-9]+$ ]]
  export RESUME_DO_IMAGE_TAG
  DOCKER=(docker)
  if ! docker info >/dev/null 2>&1; then DOCKER=(sudo -n docker); fi
  compose() {
    "${DOCKER[@]}" compose -p resume-do-cloud --env-file "$root/deploy/.env" \
      -f "$root/current/deploy/compose.cloud.yaml" "$@" < /dev/null
  }
  paused=()
  while IFS= read -r id; do [[ -z "$id" ]] || paused+=("$id"); done < <(compose ps -q resume-api resume-worker resume-web)
  [[ ${#paused[@]} -gt 0 ]] || { echo 'No running application; inspect before backup' >&2; exit 1; }
  finish() {
    local result=$?
    trap - EXIT
    "${DOCKER[@]}" start "${paused[@]}" >/dev/null || result=1
    exit "$result"
  }
  trap finish EXIT
  trap 'exit 1' HUP INT TERM
  compose stop resume-web resume-worker resume-api
  backup_data "$root/backups/daily-$(date -u +%Y%m%dT%H%M%SZ)"
  echo 'Consistent database/file backup completed; application restart requested.'
fi
