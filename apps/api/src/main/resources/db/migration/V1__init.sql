CREATE TABLE users (
  id BIGINT NOT NULL AUTO_INCREMENT,
  email VARCHAR(190) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(100) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE resumes (
  id BIGINT NOT NULL AUTO_INCREMENT,
  public_id CHAR(32) NOT NULL,
  owner_id BIGINT NOT NULL,
  title VARCHAR(100) NOT NULL,
  document JSON NOT NULL,
  appearance JSON NOT NULL,
  schema_version INT NOT NULL,
  template_id VARCHAR(32) NOT NULL,
  template_version INT NOT NULL,
  revision BIGINT NOT NULL DEFAULT 0,
  last_mutation_id VARCHAR(64) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_resumes_public_id (public_id),
  KEY idx_resumes_owner (owner_id, deleted_at, updated_at),
  CONSTRAINT fk_resumes_owner FOREIGN KEY (owner_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE export_jobs (
  id BIGINT NOT NULL AUTO_INCREMENT,
  public_id CHAR(32) NOT NULL,
  owner_id BIGINT NOT NULL,
  resume_id BIGINT NOT NULL,
  revision BIGINT NOT NULL,
  snapshot JSON NOT NULL,
  snapshot_sha256 CHAR(64) NOT NULL,
  template_id VARCHAR(32) NOT NULL,
  template_version INT NOT NULL,
  renderer_version VARCHAR(32) NOT NULL,
  filename VARCHAR(160) NOT NULL,
  idempotency_key VARCHAR(64) NOT NULL,
  status TINYINT NOT NULL DEFAULT 0,
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  lease_until DATETIME(3) NULL,
  worker_id VARCHAR(64) NULL,
  error_code VARCHAR(64) NULL,
  error_message VARCHAR(500) NULL,
  file_key VARCHAR(255) NULL,
  file_bytes BIGINT NULL,
  file_sha256 CHAR(64) NULL,
  expires_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_export_public_id (public_id),
  UNIQUE KEY uk_export_idempotency (owner_id, idempotency_key),
  KEY idx_export_queue (status, next_attempt_at, id),
  KEY idx_export_lease (lease_until),
  KEY idx_export_resume (resume_id, revision),
  CONSTRAINT fk_export_owner FOREIGN KEY (owner_id) REFERENCES users (id),
  CONSTRAINT fk_export_resume FOREIGN KEY (resume_id) REFERENCES resumes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
