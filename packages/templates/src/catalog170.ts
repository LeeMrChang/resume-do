import type { TemplateId } from '@resume-do/schema';
import type {
  TemplateGroup,
  TemplateHeaderStyle,
  TemplateLayoutKind,
  TemplateSectionStyle,
  TemplateSpec,
} from './catalog';

/**
 * 170 skins traced from Ardot「新模板 · IT技术 60 / 白领通用 60 / 电商运营 50」.
 * Each design card labels its own family and layout/header/section tokens, so the
 * tuple keeps the token order verbatim instead of pre-expanding twelve presets.
 */
type Skin = [
  id: string,
  name: string,
  group: TemplateGroup,
  kind: string,
  accent: string,
  tint: string,
  pageBg: string,
];

const HEADERS: Record<string, TemplateHeaderStyle> = {
  band: 'band-bleed',
  'band-light': 'band-light-bleed',
  'photo-left': 'photo-left',
  'photo-right': 'photo-right',
  centered: 'centered',
  art: 'art',
  block: 'block-fill',
  side: 'side',
};

const SECTIONS: Record<string, TemplateSectionStyle> = {
  rule: 'short',
  bar: 'mark',
  caps: 'blockline',
  dots: 'dots',
  icon: 'icon',
  pill: 'pill',
  timeline: 'timeline',
};

const ASIDE_SECTIONS = ['skills', 'honor', 'hobby'];

function mix(from: string, to: string, ratio: number): string {
  const a = [1, 3, 5].map(index => parseInt(from.slice(index, index + 2), 16));
  const b = [1, 3, 5].map(index => parseInt(to.slice(index, index + 2), 16));
  return `#${a
    .map((value, index) => Math.round(value + (b[index] - value) * ratio).toString(16).padStart(2, '0'))
    .join('')}`;
}

function buildSkin([id, name, group, kind, accent, tint, pageBg]: Skin): TemplateSpec {
  const [layoutToken, headerToken, sectionToken] = kind.split('/');
  const isSide = layoutToken === 'sidebar' && headerToken === 'side';
  const layout: TemplateLayoutKind =
    isSide ? 'sidebar' : layoutToken === 'timeline' ? 'timeline' : 'single';
  const header = HEADERS[headerToken];
  const section = SECTIONS[sectionToken];
  const photo = headerToken === 'band' || headerToken === 'band-light' || headerToken === 'photo-left' || headerToken === 'photo-right';
  return {
    id: id as TemplateId,
    referenceId: id,
    name,
    group,
    layout,
    header,
    section,
    accent,
    accent2: mix(accent, '#ffffff', 0.58),
    tint: headerToken === 'band-light' ? mix(accent, pageBg, 0.26) : tint,
    ink: '#1b2733',
    pageBg,
    photo,
    photoRight: headerToken === 'band' || headerToken === 'band-light',
    artBold: headerToken === 'art',
    squareNodes: layoutToken === 'timeline',
    inlineRole: true,
    plainContacts: true,
    ...(isSide
      ? {
          sidebarTone: 'dark' as const,
          sidebarBg: accent,
          sidebarInk: '#f4f8fb',
          sidebarWidthMm: 70,
          asideSections: ASIDE_SECTIONS,
        }
      : {}),
  };
}

